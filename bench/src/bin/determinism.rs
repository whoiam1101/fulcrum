//! Determinism across platforms: `sin`, `cos`, `tan` and `atan2` of `std`
//! `f64`, of `libm` and of fulcrum `FixedFloat64` on the same operands.
//!
//! `--out FILE` computes every result on this platform and writes their bits:
//! the platform name on the first line, then one line of hexadecimal bits per
//! implementation and function. `--compare DIR` reads every such file of a
//! directory and prints a Markdown table of how many results of each
//! platform differ from `linux/x86_64` (or the first platform by name when it
//! is absent), for the README (`report --determinism`).
//!
//! `std` calls the platform's math library (glibc, Apple's libm, the
//! Windows CRT), which is not required to round correctly and differs
//! between them; `libm` is the same Rust code everywhere; fulcrum uses only
//! integers.

use fulcrum::FixedFloat64;
use fulcrum_bench::inputs;
use std::fmt::Write as _;
use std::path::Path;

/// The platform the others are compared with, first when present.
const BASE: &str = "linux/x86_64";

/// Operands per function.
const N: usize = 20_000;

/// Functions, in the order of the file.
const OPS: [&str; 4] = ["sin", "cos", "tan", "atan2"];

/// Implementations, in the order of the file.
const IMPS: [&str; 3] = ["std", "libm", "fulcrum"];

/// Operands: Q32.32 raw values, half in `[-8, 8)`, half in `[-2^20, 2^20)`,
/// the second operand of `atan2` from another seed.
fn operands(seed: u64) -> Vec<i64> {
    inputs(N, seed)
        .into_iter()
        .enumerate()
        .map(|(i, x)| {
            let shift = if i % 2 == 0 { 28 } else { 11 };
            (x as i64) >> shift
        })
        .collect()
}

/// The bits of every result of one implementation and one function.
fn results(imp: &str, op: &str) -> Vec<u64> {
    let (a, b) = (operands(41), operands(42));
    let f = |raw: i64| raw as f64 / 4_294_967_296.0;
    a.iter()
        .zip(&b)
        .map(|(&x, &y)| match imp {
            "std" => match op {
                "sin" => f(x).sin().to_bits(),
                "cos" => f(x).cos().to_bits(),
                "tan" => f(x).tan().to_bits(),
                _ => f(x).atan2(f(y)).to_bits(),
            },
            "libm" => match op {
                "sin" => libm::sin(f(x)).to_bits(),
                "cos" => libm::cos(f(x)).to_bits(),
                "tan" => libm::tan(f(x)).to_bits(),
                _ => libm::atan2(f(x), f(y)).to_bits(),
            },
            _ => {
                let (x, y) = (FixedFloat64::from_bits(x), FixedFloat64::from_bits(y));
                let r = match op {
                    "sin" => x.sin(),
                    "cos" => x.cos(),
                    "tan" => x.tan(),
                    _ => x.atan2(y),
                };
                r.to_bits() as u64
            }
        })
        .collect()
}

/// `os/arch` of this build, such as `linux/x86_64`.
fn platform() -> String {
    format!("{}/{}", std::env::consts::OS, std::env::consts::ARCH)
}

fn write(path: &Path) {
    let mut s = platform();
    s.push('\n');
    for imp in IMPS {
        for op in OPS {
            for v in results(imp, op) {
                let _ = write!(s, "{:016x}", v);
            }
            s.push('\n');
        }
    }
    std::fs::write(path, s).expect("write results");
}

/// One platform's file: its name and the bits of every row.
fn read(path: &Path) -> (String, Vec<Vec<u64>>) {
    let text = std::fs::read_to_string(path).expect("read results");
    let mut lines = text.lines();
    let name = lines.next().expect("platform line").to_string();
    let rows = lines
        .map(|l| {
            (0..l.len() / 16)
                .map(|i| u64::from_str_radix(&l[16 * i..16 * i + 16], 16).expect("hex"))
                .collect()
        })
        .collect();
    (name, rows)
}

/// The Markdown table of the files of `dir`.
fn compare(dir: &Path) -> String {
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("read dir")
        .map(|e| e.expect("entry").path())
        .filter(|p| p.is_file())
        .collect();
    files.sort();
    let mut platforms: Vec<(String, Vec<Vec<u64>>)> = files.iter().map(|p| read(p)).collect();
    platforms.sort_by_key(|(name, _)| (name != BASE, name.clone()));
    let (base_name, base) = &platforms[0];
    let mut s = String::new();
    let _ = writeln!(
        s,
        "Results that differ bit for bit from `{}`, of {} operands per function \
         (Q32.32 values in `[-8, 8)` and `[-2^20, 2^20)`, the same `f64` for the floats). \
         `std` calls the platform's math library; `libm` is the same Rust code everywhere; fulcrum uses only integers. \
         Generated by [`bench/src/bin/determinism.rs`](bench/src/bin/determinism.rs) on the CI runners.\n",
        base_name, N
    );
    s.push_str("| Function | Implementation |");
    for (name, _) in &platforms[1..] {
        let _ = write!(s, " `{}` |", name);
    }
    s.push_str("\n|---|---|");
    for _ in &platforms[1..] {
        s.push_str("---:|");
    }
    s.push('\n');
    for (i, imp) in IMPS.iter().enumerate() {
        for (j, op) in OPS.iter().enumerate() {
            let row = i * OPS.len() + j;
            let _ = write!(s, "| `{}` | {} |", op, imp);
            for (_, rows) in &platforms[1..] {
                let differ = rows[row]
                    .iter()
                    .zip(&base[row])
                    .filter(|(a, b)| a != b)
                    .count();
                let _ = write!(s, " {} |", differ);
            }
            s.push('\n');
        }
    }
    s
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("--out") => write(Path::new(&args[2])),
        Some("--compare") => print!("{}", compare(Path::new(&args[2]))),
        _ => {
            eprintln!("usage: determinism --out FILE | --compare DIR");
            std::process::exit(2);
        }
    }
}
